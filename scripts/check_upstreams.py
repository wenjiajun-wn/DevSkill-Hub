"""Detect upstream skill, installation, and license drift without renewing reviews."""

import argparse
from http.client import HTTPException
import json
import os
from pathlib import Path
import re
import sys
import time
from urllib.error import HTTPError, URLError
from urllib.parse import quote
from urllib.request import Request, urlopen

try:
    from .catalog import CATALOG_PATH, CatalogError, load_catalog, validate
    from .transaction import commit_files, write_lock
except ImportError:
    from catalog import CATALOG_PATH, CatalogError, load_catalog, validate
    from transaction import commit_files, write_lock


def fetch_tree(repository, branch, token=None, opener=urlopen, sleeper=time.sleep):
    headers = {"User-Agent": "DevSkill-Hub-upstream-check", "Accept": "application/vnd.github+json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = Request(f"https://api.github.com/repos/{repository}/git/trees/{quote(branch, safe='')}?recursive=1", headers=headers)
    for attempt in range(3):
        try:
            with opener(request, timeout=25) as response:
                body = json.load(response)
            if not isinstance(body, dict) or not isinstance(body.get("tree"), list) or body.get("truncated") is not False:
                raise CatalogError(f"{repository}: incomplete or invalid upstream tree; no clean bill of health recorded")
            if any(not isinstance(item, dict) or not isinstance(item.get("path"), str) or
                   not isinstance(item.get("sha"), str) or not re.fullmatch(r"[0-9a-f]{40}", item["sha"])
                   for item in body["tree"]):
                raise CatalogError(f"{repository}: malformed upstream tree entries")
            return {item["path"]: item["sha"] for item in body["tree"]}
        except HTTPError as exc:
            if exc.code in (500, 502, 503, 504) and attempt < 2:
                sleeper(2 ** attempt)
                continue
            raise CatalogError(f"{repository}: GitHub HTTP {exc.code}; check access/rate limits before retrying") from None
        except (URLError, TimeoutError, OSError, HTTPException):
            if attempt < 2:
                sleeper(2 ** attempt)
                continue
            raise CatalogError(f"{repository}: upstream request failed after 3 attempts") from None
        except CatalogError:
            raise
        except (ValueError, KeyError, TypeError):
            raise CatalogError(f"{repository}: malformed GitHub tree response") from None


def inspect_catalog(data, fetcher):
    findings = []
    for repository, meta in data["repositories"].items():
        baseline = meta.get("monitoring", {}).get("files")
        if not isinstance(baseline, dict) or not baseline:
            raise CatalogError(f"{repository}: missing reviewed monitoring baseline")
        tree = fetcher(repository, meta["default_branch"])
        for path, expected in baseline.items():
            actual = tree.get(path)
            if actual != expected:
                kind = "added" if expected is None else "removed" if actual is None else "changed"
                findings.append({"repository": repository, "path": path, "status": kind,
                                 "reviewed_sha": expected, "current_sha": actual})
    return findings


def report(data, findings):
    lines = ["# Upstream change monitoring / 上游变更监测", "<!-- Generated by scripts/check_upstreams.py. -->",
             "This report compares Git blob/tree hashes against explicitly recorded review baselines. Skill directories include scripts and references; README/plugin metadata and license paths are monitored separately. A missing license becoming available is a change too. Successful checks do not renew content reviews or installation/effectiveness claims.",
             "比较已记录基线与上游文件/目录哈希。检测 Skill 及配套资料、安装说明、插件元数据和许可证的新增、删除或修改。检测成功不会自动更新人工审查日期或测试结论。"]
    if findings:
        lines += ["## Changes requiring review / 需要复审", "| Repository | Path | Status |\n| --- | --- | --- |"]
        for finding in findings:
            repo, path = finding["repository"], finding["path"]
            lines.append(f"| [{repo}](https://github.com/{repo}) | `{path}` | {finding['status']} |")
        lines.append("\nReinspect the changed files, rerun relevant smoke tests, then update the baseline and review evidence in a human-reviewed PR. Do not reset hashes just to silence a warning.\n\n重新阅读变更内容并运行相关测试后，在人工审查的 PR 中更新基线，不要仅为清除警告而替换哈希。")
    else:
        lines.append("## Result / 结果\n\nNo monitored changes relative to the recorded baselines. / 与记录的基线相比，未检测到所监测内容的变化。")
    lines += ["\n## Reviewed baselines / 复审基线", "| Repository | Baseline recorded (UTC) | Monitored paths |\n| --- | --- | ---: |"]
    for repo, meta in data["repositories"].items():
        baseline = meta["monitoring"]
        lines.append(f"| [{repo}]({meta['url']}) | {baseline['reviewed_at']} | {len(baseline['files'])} |")
    lines.append("\nThe weekly workflow proposes this report through a PR only when its contents change. Network/API errors fail the job and preserve the last report. Manual review remains necessary for changes; this monitor handles detection.\n\n每周检查，仅报告内容变化时提出 PR。网络/API 错误会使任务失败并保留原报告。变更的判断仍需人工完成，自动化负责发现变化。")
    return "\n\n".join(lines[:4]) + "\n\n" + "\n".join(lines[4:]) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", default=CATALOG_PATH)
    parser.add_argument("--fail-on-drift", action="store_true")
    args = parser.parse_args(argv)
    try:
        root = Path(args.catalog).resolve().parent.parent
        with write_lock(root):
            data = load_catalog(args.catalog)
            errors = validate(data)
            if errors:
                raise CatalogError("; ".join(errors))
            token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
            findings = inspect_catalog(data, lambda repo, branch: fetch_tree(repo, branch, token))
            commit_files({root / "docs/upstream-status.md": report(data, findings)}, root)
        print(f"Checked {len(data['repositories'])} repositories; {len(findings)} changed monitored paths.")
        return 1 if findings and args.fail_on_drift else 0
    except (CatalogError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
