def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def format_stars(stars):
    if stars is None:
        return "N/A"
    return f"{stars / 1000:.1f}k" if stars >= 1000 else str(stars)


def license_label(info):
    return info["spdx"] + (" (declaration only)" if info.get("evidence_status") == "declaration-only" else "")


def replace_block(text, name, value):
    start, end = f"<!-- BEGIN {name} -->", f"<!-- END {name} -->"
    if text.count(start) != 1 or text.count(end) != 1 or text.index(start) > text.index(end):
        raise CatalogError(f"Expected one ordered pair of generated markers: {name}")
    before, rest = text.split(start)
    _, after = rest.split(end)
    return before + start + "\n" + value.rstrip() + "\n" + end + after


def table(data, category, zh=False, prefix="catalog/"):
    headers = ("排名", "Skill", "简介", "仓库 Stars", "安装") if zh else ("Rank", "Skill", "Description", "Repository Stars", "Install")
    lines = ["| " + " | ".join(headers) + " |", "| ---: | --- | --- | ---: | --- |"]
    entries = [s for s in data["skills"] if s["category"] == category]
    for rank, skill in enumerate(entries, 1):
        repository = data["repositories"][skill["repository"]]
        name = f"[{skill['name']}]({skill['skill_url'] or repository['url']})"
        description = skill["description_zh" if zh else "description"]
        stars = format_stars(repository["stars"])
        if repository["stars"] is not None:
            stars = f"[{stars}]({repository['url']})"
        install = f"[{'安装' if zh else 'Install'}]({prefix}{category}.md#{skill['id']})" if skill["install"]["command"] else "N/A"
        lines.append("| " + " | ".join(map(cell, (rank, name, description, stars, install))) + " |")
    return "\n".join(lines)


def catalog_section(data, zh=False):
    times = [m["stars_updated_at"] for m in data["repositories"].values() if m["stars_updated_at"]]
    if times:
        period = min(times) if min(times) == max(times) else f"{min(times)} → {max(times)}"
    else:
        period = "N/A"
    intro = (f"Star 数据采集时间（UTC）：**{period}**。" if zh else f"Stars observed (UTC): **{period}**.")
    caveat = ("Stars 属于来源仓库；它不是单个 Skill 的评分，也不代表实际效果。N/A 表示没有已验证数据。" if zh else "Stars belong to the source repository, not the individual skill. They measure popularity, not effectiveness. N/A means no verified data.")
    sections = [intro + "\n\n" + caveat]
    for category, labels in data["categories"].items():
        heading = labels["name_zh" if zh else "name"]
        # Explicit stable anchors keep the bilingual navigation independent of GitHub slug rules.
        sections.append(f'<a id="{category}"></a>\n\n## {heading}\n\n' + table(data, category, zh))
    return "\n\n".join(sections)


def summary(data, zh=False):
    counts = [(k, sum(s["category"] == k for s in data["skills"])) for k in data["categories"]]
    parts = [f"{data['categories'][k]['name_zh' if zh else 'name']} {n}" for k, n in counts]
    installed = sum(s["verification"]["installation_tested"] for s in data["skills"])
    if zh:
        return f"**v{data['version']} · {len(data['skills'])} 个 Skills · {len(data['repositories'])} 个来源仓库**\n\n" + " / ".join(parts) + f"\n\n{installed} 个条目通过隔离安装冒烟检查；[实测范围与限制](docs/evaluations/functional-smoke.md)包含已发现的上游缺陷。"
    return f"**v{data['version']} · {len(data['skills'])} skills · {len(data['repositories'])} source repositories**\n\n" + " / ".join(parts) + f"\n\n{installed} entries passed isolated installation smoke checks. Read the [evaluation scope and limitations](docs/evaluations/functional-smoke.md), including known upstream issues."


def category_page(data, category):
    labels = data["categories"][category]
    lines = [f"# {labels['name']} / {labels['name_zh']}",
             "[Home](../README.md) · [中文首页](../README.zh-CN.md) · [Installation guide](../docs/how-to-install.md)",
             "<!-- Generated by scripts/render_catalog.py. Edit catalog/skills.yaml. -->",
             table(data, category, prefix=""),
             "Repository stars are snapshots. Each entry records its own observation and review dates.\n\n仓库 Star 为采集时的快照；元数据审查、安装实测、效果评估分别记录。"]
    for s in (s for s in data["skills"] if s["category"] == category):
        repo = data["repositories"][s["repository"]]
        v, install = s["verification"], s["install"]
        license_info = repo["license"]
        source = f"https://github.com/{s['repository']}/blob/{s['source_commit']}/{s['skill_path']}" if s.get("source_commit") else repo["url"]
        lines.extend([f'<a id="{s["id"]}"></a>\n\n## {s["name"]}',
                      s["description"] + "\n\n" + s["description_zh"],
                      f"**Source / 来源:** [{s['repository']}]({repo['url']}) · [SKILL.md]({s['skill_url'] or repo['url']}) · [reviewed revision]({source})",
                      f"**Stars:** {repo['stars'] if repo['stars'] is not None else 'N/A'} · **Observed (UTC):** {repo['stars_updated_at'] or 'N/A'}",
                      f"**License:** [{license_label(license_info)}]({license_info['url']}) ({license_info['scope']}). {license_info['note']}",
                      f"**Skill last modified (UTC):** {s.get('skill_updated_at') or 'N/A'} · **Reviewed (UTC):** {v['last_reviewed'] or 'N/A'}",
                      "**Use when / 适用场景**\n\n" + "\n".join(f"- {x}" for x in s["use_cases"]) + "\n\n" + "\n".join(f"- {x}" for x in s["use_cases_zh"]),
                      "**Install / 安装**"])
        if install["command"]:
            lines.extend(["```text\n" + install["command"].rstrip() + "\n```",
                          f"[Upstream instructions / 上游安装说明]({install['documentation_url']})",
                          install["notes"] + "\n\n" + install["notes_zh"]])
        else:
            lines.append("N/A — no verified installation command. / 暂无经核实的安装命令。")
        state = lambda key: "yes" if v[key] else "no"
        lines.append(f"**Verification:** metadata reviewed: {state('metadata')}; install instructions reviewed: {state('installation')}; installation executed: {state('installation_tested')}; effectiveness tested: {state('effectiveness')}.")
        if v.get("installation_test_report_url"):
            lines.append(f"[Installation evidence / 安装实测]({v['installation_test_report_url']}) · [Scoped {v['smoke_scope']} evidence / 限定范围评估]({v['smoke_report_url']})")
        lines.append(s["review_notes"] + "\n\n" + s["review_notes_zh"])
    return "\n\n".join(lines).rstrip() + "\n"


def notices(data):
    lines = ["# Third-party notices", "<!-- Generated by scripts/render_catalog.py. Edit catalog/skills.yaml. -->",
             "DevSkill Hub links to upstream projects. No third-party SKILL.md files, scripts, artwork, or repositories are redistributed here. Descriptions are original editorial summaries. This directory is independent and does not imply endorsement by the upstream authors or by Andrej Karpathy.",
             "Our MIT license covers our original code and documentation only. Upstream licenses and file-level exceptions continue to apply when you install or redistribute upstream material. License evidence is a reviewed snapshot, not a legal opinion.",
             "| Repository | License evidence | Scope / caveat |\n| --- | --- | --- |"]
    for repo, meta in sorted(data["repositories"].items()):
        info = meta["license"]
        lines.append(f"| [{repo}]({meta['url']}) | [{license_label(info)}]({info['url']}) | {cell(info['scope'] + ': ' + info['note'])} |")
    lines.extend(["## Attribution policy", "Names identify their respective projects and owners. We do not claim ownership of them. If you find an incorrect attribution or licensing statement, open an issue with a link to the authoritative upstream file. See [verification records](docs/verification.md) for reviewed revisions and unresolved issues."])
    return "\n\n".join(lines[:4]) + "\n\n" + "\n".join(lines[4:-2]) + "\n\n" + "\n\n".join(lines[-2:]) + "\n"


def review_report(data):
    lines = ["# Upstream verification record / 上游核查记录",
             "<!-- Generated by scripts/render_catalog.py. Edit catalog/skills.yaml. -->",
             "Repository metadata was read from the public GitHub REST API; SKILL.md frontmatter and bodies, license evidence, and upstream installation documentation were inspected. SKILL.md last-modified dates come from the latest commit affecting that path, not repository activity. Star refreshes do not renew content-verification dates.",
             "通过 GitHub API 和实际文件核查；已执行隔离安装，并另附限定范围的工具冒烟/人工演练报告。未开展对照模型效果评测，冒烟通过不代表生产质量或跨模型提升。",
             "| Skill | Category | Reviewed revision | Metadata | Install docs | Install executed | Effectiveness |\n| --- | --- | --- | --- | --- | --- | --- |"]
    for s in data["skills"]:
        v = s["verification"]
        ref = f"https://github.com/{s['repository']}/blob/{s['source_commit']}/{s['skill_path']}" if s.get("source_commit") else data["repositories"][s["repository"]]["url"]
        yes = lambda key: "yes" if v[key] else "no"
        lines.append(f"| [{s['name']}]({s['skill_url'] or ref}) | {s['category']} | [{(s.get('source_commit') or 'N/A')[:7]}]({ref}) | {yes('metadata')} | {yes('installation')} | {yes('installation_tested')} | {yes('effectiveness')} |")
    lines.append("\n## Adjustments and limitations / 调整与限制\n")
    for s in data["skills"]:
        lines.append(f"### {s['name']}\n\n{s['review_notes']}\n\n{s['review_notes_zh']}\n\nReviewed: {s['verification']['last_reviewed'] or 'N/A'}. [Install evidence]({s['install']['documentation_url'] or data['repositories'][s['repository']]['url']}).\n")
    lines.append("## Repository activity snapshot\n\nThese API timestamps describe the repository, not the individual skill. `updated_at` may change for metadata or stars; `pushed_at` records the latest repository push at review time.\n\n| Repository | updated_at (UTC) | pushed_at (UTC) |\n| --- | --- | --- |")
    for repo, meta in sorted(data["repositories"].items()):
        lines.append(f"| [{repo}]({meta['url']}) | {meta['updated_at'] or 'N/A'} | {meta['pushed_at'] or 'N/A'} |")
    return "\n".join(lines).rstrip() + "\n"


def render_all(data, root=ROOT):
    root = Path(root)
    outputs = {}
    for filename, zh in (("README.md", False), ("README.zh-CN.md", True)):
        path = root / filename
        text = path.read_text(encoding="utf-8")
        text = replace_block(text, "summary", summary(data, zh))
        example = next((s for s in data["skills"] if s["id"] == "frontend-ui-engineering"), data["skills"][0])
        intro = "例如，上游提供以下安装入口" if zh else "For example, upstream documents this installation entry point"
        install = example["install"]
        block = f"{intro} ([{'来源' if zh else 'source'}]({install['documentation_url']})):\n\n```text\n{install['command'] or 'N/A'}\n```"
        text = replace_block(text, "quick-install", block)
        text = replace_block(text, "catalog", catalog_section(data, zh))
        outputs[path] = text
    for category in data["categories"]:
        outputs[root / "catalog" / f"{category}.md"] = category_page(data, category)
    for filename, zh in (("introducing-devskill-hub.md", False), ("introducing-devskill-hub.zh-CN.md", True)):
        path = root / "docs" / "blog" / filename
        lines = []
        for category, labels in data["categories"].items():
            entries = sorted((s for s in data["skills"] if s["category"] == category), key=lambda s: s["id"])
            names = ", ".join(f"[{s['name']}]({s['skill_url'] or data['repositories'][s['repository']]['url']})" for s in entries)
            lines.append(f"- **{labels['name_zh' if zh else 'name']}**: {names}.")
        outputs[path] = replace_block(path.read_text(encoding="utf-8"), "edition-list", "\n".join(lines))
    outputs[root / "THIRD_PARTY_NOTICES.md"] = notices(data)
    outputs[root / "docs" / "verification.md"] = review_report(data)
    return outputs


def run(args):
    data = load_catalog(args.catalog)
    errors = validate(data)
    if errors:
        raise CatalogError("; ".join(errors))
    root = Path(args.catalog).resolve().parent.parent
    outputs = render_all(data, root=root)
    stale = [path.name for path, text in outputs.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    if args.check and stale:
        raise CatalogError("Generated files are stale: " + ", ".join(stale))
    if not args.check:
        commit_files(outputs, root)
    print(f"Generated documentation {'checked' if args.check else 'updated'} ({len(outputs)} files).")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", default=CATALOG_PATH)
    parser.add_argument("--check", action="store_true", help="Fail if generated documentation is stale")
    args = parser.parse_args(argv)
    try:
        with write_lock(Path(args.catalog).resolve().parent.parent):
            return run(args)
    except (CatalogError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
